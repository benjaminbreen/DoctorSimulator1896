// Keep garment construction in its atlas; repeat fine cloth independently.
import {mkdir, writeFile, copyFile, readdir} from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import {createIO} from '../lib/glb-pipeline.mjs';

const root=path.resolve(import.meta.dirname,'../..');
const source=path.join(root,'assets/source/clothing-fabrics-2026-11-03');
const out=path.join(root,'game/public/textures/clothing');
const lab=path.join(root,'character-lab/public/textures/clothing');
await mkdir(out,{recursive:true});await mkdir(lab,{recursive:true});
const n=1024,tau=Math.PI*2,manifest={fabrics:{},atlases:{}};
async function save(file,data,options={}){
  const image=sharp(data,options);
  await image.webp({quality:94,lossless:!file.includes('albedo')&&!file.startsWith('atlas-'),effort:6}).toFile(path.join(out,file));
  await copyFile(path.join(out,file),path.join(lab,file));
}
for(const kind of ['wool','herringbone','silk']){
  const tile=await sharp(path.join(source,kind+'-source.png')).resize(n/2,n/2).grayscale().toBuffer();
  const pieces=await Promise.all([sharp(tile).toBuffer(),sharp(tile).flop().toBuffer(),sharp(tile).flip().toBuffer(),sharp(tile).flip().flop().toBuffer()]);
  const {data:pixels}=await sharp({create:{width:n,height:n,channels:3,background:'white'}})
    .composite(pieces.map((input,i)=>({input,left:i%2*n/2,top:Math.floor(i/2)*n/2}))).removeAlpha().raw().toBuffer({resolveWithObject:true});
  const mean=pixels.reduce((a,b)=>a+b,0)/pixels.length;
  // A neutral mean keeps the original garment colour when changing fabric.
  for(let i=0;i<pixels.length;i++)pixels[i]=Math.max(180,Math.min(255,238+(pixels[i]-mean)*(kind==='herringbone'?.62:.42)));
  await save(kind+'-albedo.webp',pixels,{raw:{width:n,height:n,channels:3}});
  const height=new Float32Array(n*n),normal=Buffer.alloc(n*n*3),roughness=Buffer.alloc(n*n);
  for(let y=0;y<n;y++)for(let x=0;x<n;x++){
    const u=x/n,v=y/n,dir=Math.floor(u*16)%2?-1:1;
    const grain=Math.sin(tau*(u*173+v*127))*.08;
    height[y*n+x]=kind==='silk'?Math.cos(tau*v*192)*.30+grain*.25
      :kind==='herringbone'?Math.cos(tau*(u*128+dir*v*64))*.55+Math.cos(tau*v*128)*.18+grain
      :Math.cos(tau*(u+v)*128)*.34+Math.cos(tau*(u-v)*96)*.10+grain;
  }
  for(let y=0;y<n;y++)for(let x=0;x<n;x++){
    const i=y*n+x,dx=(height[y*n+(x+1)%n]-height[y*n+(x+n-1)%n])*.65;
    const dy=(height[((y+1)%n)*n+x]-height[((y+n-1)%n)*n+x])*.65;
    const length=Math.hypot(dx,dy,1);
    normal[i*3]=Math.round((-dx/length*.5+.5)*255);normal[i*3+1]=Math.round((dy/length*.5+.5)*255);normal[i*3+2]=Math.round((1/length*.5+.5)*255);
    roughness[i]=Math.round((.96+height[i]*.025)*255);
  }
  await save(kind+'-normal.webp',normal,{raw:{width:n,height:n,channels:3}});
  await save(kind+'-roughness.webp',roughness,{raw:{width:n,height:n,channels:1}});
  manifest.fabrics[kind]={size:n,tileMetres:.08};
}

const io=await createIO(),seen=new Set();
const modelDir=path.join(root,'game/public/models/characters');
for(const file of (await readdir(modelDir)).filter(f=>f.endsWith('.glb')&&!f.includes('mobile'))){
  const document=await io.read(path.join(modelDir,file));
  for(const material of document.getRoot().listMaterials()){
    if(!['Patient_MaleFabric','Patient_DressFabric','Patient_SeatedDressFabric'].includes(material.getName()))continue;
    const texture=material.getBaseColorTexture();if(!texture||seen.has(texture.getName()))continue;
    seen.add(texture.getName());
    const name=texture.getName(),filename='atlas-'+name.replace(/[^a-zA-Z0-9_-]/g,'-')+'.webp';
    // Remove the donor's coarse painted grain, retaining broader folds and trim.
    const clean=await sharp(texture.getImage()).blur(2.4).toBuffer();
    await save(filename,clean);
    manifest.atlases[name]='/textures/clothing/'+filename;
  }
}
await writeFile(path.join(out,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
await copyFile(path.join(out,'manifest.json'),path.join(lab,'manifest.json'));
await writeFile(path.join(root,'shared/characters/clothingAtlases.js'),
  '// Generated by scripts/materials/build-clothing-fabrics.mjs.\nexport const CLOTHING_ATLASES = '+JSON.stringify(manifest.atlases,null,2)+';\n');
console.log(`CLOTHING_FABRICS_OK 3 fabrics, ${seen.size} garment atlases`);
